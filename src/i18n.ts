const SUPPORTED_SET = new Set<string>(LANGUAGE_OPTIONS.map((l) => l.code));

export function isSupportedLanguage(val: unknown): val is Language {
  return typeof val === 'string' && SUPPORTED_SET.has(val);
}

export function parseLanguage(val: unknown, fallback: Language = 'en'): Language {
  return isSupportedLanguage(val) ? val : fallback;
}

export function getLanguageLabel(lang: Language): string {
  const match = LANGUAGE_OPTIONS.find((l) => l.code === lang);
  if (!match) return 'English';
  return match.code === 'en' ? 'English' : `${match.englishName} (${match.nativeName})`;
}

